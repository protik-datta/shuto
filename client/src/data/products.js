const slugify = (text) =>
  text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");

const buildReviews = (index) => {
  const count = 3 + (index % 4);
  return Array.from({ length: count }, (_, offset) => {
    const base = REVIEW_POOL[(index * 5 + offset * 3) % REVIEW_POOL.length];
    const day = 1 + ((index * 7 + offset * 11) % 27);
    const month = 1 + ((index + offset * 2) % 9);
    return {
      id: `r-${index}-${offset}`,
      ...base,
      date: `2026-${String(month).padStart(2, "0")}-${String(day).padStart(2, "0")}`,
    };
  });
};

export const PRODUCTS = ROWS.map(
  (
    [
      name,
      category,
      department,
      collection,
      price,
      originalPrice,
      material,
      colorNames,
      sizeSet,
      note,
      flags,
    ],
    index,
  ) => {
    const id = index + 1;
    const slug = slugify(name);
    const reviews = buildReviews(index);
    const average =
      reviews.reduce((sum, review) => sum + review.rating, 0) / reviews.length;
    const stock = id % 11 === 0 ? 0 : id % 7 === 0 ? 4 : 18 + (id % 5) * 6;
    return {
      id,
      slug,
      name,
      category,
      department,
      collection,
      price,
      originalPrice,
      currency: "BDT",
      description: `${note}. Made from ${material.toLowerCase()} and designed to be worn often.`,
      material,
      care: CARE[category] ?? CARE.default,
      colors: colorNames.map((colorName) => ({
        name: colorName,
        hex: COLOR_HEX[colorName],
      })),
      sizes: SIZE_SETS[sizeSet],
      images: productImages(slug),
      rating: Math.round(average * 10) / 10,
      reviewCount: 14 + ((id * 13) % 90),
      reviews,
      isNew: flags.includes("n"),
      isFeatured: flags.includes("f"),
      isBestSeller: flags.includes("b"),
      stock,
      sku: `SH-${category.slice(0, 3).toUpperCase()}-${String(id).padStart(3, "0")}`,
      tags: [
        category,
        department,
        collection,
        material.split(" ").pop().toLowerCase(),
        ...colorNames.map((c) => c.toLowerCase()),
      ],
    };
  },
);
